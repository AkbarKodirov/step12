import json,re
res=json.load(open('clean.json'))
names=['Expressions','Linear Equations','Linear System of Equations','Linear Functions','Linear Inequalities','Polynomials','Exponents&Radicals','Functions&Function Notation','Exponential Functions','Quadratics','Percent; Ratio&Proportion','Unit Conversion','Probability','Mean, Median, Mode, Range','Scatterplots','Research organizing','Lines&Angles','Triangles','Trignometry','Circles','Areas&Volumes']
base={0:'EQX',1:'LE1',2:'SYS',3:'LF',4:'INEQ',5:'EQX',6:'EQX',7:'NLF',8:'NLF',9:'NLE',11:'RAT',12:'PROB',13:'ONEV',14:'TWOV',16:'LAT',18:'RT',19:'CIR',20:'AREA'}
def code(r):
    s=r['sec'];t=' '.join(r['stemlines'])
    if s in base: return base[s]
    if s==10: return 'PCT' if re.search(r'%|percent',t,re.I) else 'RAT'
    if s==15: return 'INF' if re.search(r'margin of error|survey|sample|estimate',t,re.I) else 'EVAL'
    if s==17: return 'RT' if re.search(r'\bsin|\bcos|\btan|hypotenuse|pythag|right triangle|right angle',t,re.I) else 'LAT'
EXCL={(6,8),(10,40)}  # garbled stacked math that the rules could not recover
def sane(r):
    t=' '.join(r['stemlines'])
    if r['sec'] in (6,8): return False   # exponent-heavy: stacked exponents are not recoverable from the text
    if not r['opts'] and r['ans'].startswith('-') and re.search(r'positive (integer|number|constant|value)',t): return False
    return True
ok=[r for r in res if not r['flags'] and (r['sec'],r['n']) not in EXCL and sane(r)]
out=['# Math Book 2.0 (real exam questions collection): questions whose text was cleanly recovered. Generated by scripts/mathbook2/*.py; format as scripts/hardbook.']
for r in ok:
    ans=r['ans']
    out.append(f"@{r['sec']}-{r['n']} | {code(r)} | {ans}")
    out+=r['stemlines']
    for i,o in enumerate(r['opts']): out.append('ABCD'[i]+') '+o)
    out.append('')
open('/home/user/step12/scripts/mathbook2/mathbook2.txt','w').write('\n'.join(out))
skip=[{'section':names[r['sec']],'n':r['n'],'source':r['src'],'flags':r['flags']} for r in res if r['flags']]+[{'section':names[r['sec']],'n':r['n'],'source':r['src'],'flags':['garbled']} for r in res if not r['flags'] and r not in ok]
json.dump(skip,open('/home/user/step12/scripts/mathbook2/skipped.json','w'),indent=0)
print(len(ok),len(skip))
from collections import Counter
print(Counter(code(r) for r in ok))
